-- F19: 独習モード。
--
-- 「初等中等の教科学習で、単元データを根拠にした擬似メンバーに説明し、議論して理解を深める」
-- (要件定義書4章、シナリオC)。学習セッション自体は既にF05で学習者1人につき1セッションの
-- 構造になっており、擬似メンバーの仕組み(F02〜F05)もそのまま使い回せるため、
-- 新しい対話機構は作らない。教師が授業(=シナリオCの「単元」に相当する粒度)を作成する時点で
-- 「グループワーク」か「独習」かを選び、それに応じて学習者側の画面の説明文と、作成される
-- learning_sessions.mode(既にF01の初期スキーマでsolo_studyを許容済み)を切り替える。
--
-- 独習モードでの具体的な違い(コードでは表現しない、運用上の使い分け):
--  - ペルソナ(F03/F04)は「まだ分からない仲間」役として教師が設定する(プロフィール/立場欄を使う)
--  - 説明の質へのフィードバックは、F07の評価の観点(criteria)に「根拠の明確さ」「用語の正しさ」
--    「誤りの有無」といった観点を教師が設定することで対応する(F07の仕組みをそのまま使う)
alter table courses
  add column if not exists mode text not null default 'group'
    check (mode in ('group', 'solo_study'));
